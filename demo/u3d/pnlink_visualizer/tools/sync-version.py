"""Generate display/build constants and Unity's bundleVersion from version.json."""
import argparse
import json
from pathlib import Path
import re


def synchronize(project, write=False):
    project=Path(project).resolve()
    data=json.loads((project/'version.json').read_text(encoding='utf-8'))
    assert re.fullmatch(r'\d+\.\d+\.\d+',data['version']), 'Use a three-part product version'
    assert data['tag']=='pnlink-visualizer-v'+data['version']
    assert isinstance(data['build'],int) and data['build']>0
    constants='// Generated by tools/sync-version.py from version.json.\npublic static class VisualizerBuildInfo\n{\n'
    for name,value in [('Product',data['product']),('Version',data['version']),('Tag',data['tag']),('Stage',data['stage'])]:
        constants+='    public const string '+name+' = '+json.dumps(value,ensure_ascii=False)+';\n'
    constants+='    public const int Build = '+str(data['build'])+';\n}\n'
    generated=project/'Assets/Scripts/VisualizerBuildInfo.cs'
    settings=project/'ProjectSettings/ProjectSettings.asset'
    current=settings.read_text(encoding='utf-8-sig')
    expected,count=re.subn(r'(?m)^  bundleVersion: .*$', '  bundleVersion: '+data['version'],current)
    assert count==1, 'Expected one Unity bundleVersion'
    if write:
        generated.write_text(constants,encoding='utf-8')
        if expected!=current: settings.write_text(expected,encoding='utf-8')
    else:
        assert generated.is_file() and generated.read_text(encoding='utf-8')==constants, 'Run tools/sync-version.py --write'
        assert expected==current, 'Unity bundleVersion is stale; run tools/sync-version.py --write'
    return data


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    result=synchronize(Path(__file__).resolve().parents[1],args.write)
    print(json.dumps(dict(passed=True,version=result['version'],build=result['build'],tag=result['tag'])))
